class FakeTokenizer:
    name_or_path = "fake-tokenizer"

    def __init__(self) -> None:
        self.prompts = []

    def apply_chat_template(self, messages, tokenize=False, add_generation_prompt=False):
        assert tokenize is False
        assert add_generation_prompt is True
        return "\n".join(f"{item['role']}::{item['content']}" for item in messages) + "\nassistant::"

    def __call__(self, prompt, return_tensors="pt", truncation=False):
        assert return_tensors == "pt"
        assert truncation is False
        self.prompts.append(prompt)
        return {"input_ids": [[1, 2, 3, 4]]}

    def decode(self, token_ids, skip_special_tokens=True):
        assert skip_special_tokens is True
        assert list(token_ids) == [9, 10, 11]
        return "Native causal response."


class FakeModel:
    name_or_path = "fake-causal-model"

    def generate(self, **kwargs):
        assert kwargs["input_ids"] == [[1, 2, 3, 4]]
        assert kwargs["do_sample"] is False
        assert kwargs["max_new_tokens"] == 64
        return [[1, 2, 3, 4, 9, 10, 11]]


class PrefixMismatchModel:
    name_or_path = "fake-prefix-mismatch"

    def generate(self, **kwargs):
        return [[1, 2, 99, 9]]


