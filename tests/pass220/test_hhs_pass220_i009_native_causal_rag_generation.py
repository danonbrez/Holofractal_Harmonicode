class FakeGenerationService:
    def __init__(self) -> None:
        self.calls = []

    def status(self):
        return {
            "configured": True,
            "loaded": True,
            "ready": True,
            "model_id": "fake-native-causal",
        }

    def generate(self, messages, *, retrieval_context=None, max_new_tokens=None):
        self.calls.append({
            "messages": [dict(item) for item in messages],
            "retrieval_context": retrieval_context,
            "max_new_tokens": max_new_tokens,
        })
        response = "Generated by the native causal model. " * 80
        return {
            "response": response,
            "receipt": {
                "receipt_root_hash72": "r" * 72,
                "causal_prefix_verified": True,
                "generated_token_count": 400,
                "canonical_vm81_mutation_authority": False,
            },
            "status": self.status(),
        }


def test_native_causal_generation_decodes_only_new_tokens_and_witnesses_receipt():
    tokenizer = FakeTokenizer()
    service = NativeCausalLMGenerationService(
        tokenizer=tokenizer,
        model=FakeModel(),
        model_id="fake-causal-model",
        max_new_tokens=64,
    )

    result = service.generate(
        [
            {"role": "system", "content": "governed system"},
            {"role": "user", "content": "hello"},
        ],
        retrieval_context="candidate context",
    )

    assert result["response"] == "Native causal response."
    receipt = result["receipt"]
    assert receipt["input_token_count"] == 4
    assert receipt["generated_token_count"] == 3
    assert receipt["causal_prefix_verified"] is True
    assert receipt["natural_language_egress_only"] is True
    assert receipt["canonical_vm81_mutation_authority"] is False
    assert receipt["canonical_hash72_mutation_authority"] is False
    assert receipt["canonical_hash216_mutation_authority"] is False
    assert len(receipt["receipt_root_hash72"]) == 72
    assert "Retrieved candidate context follows" in tokenizer.prompts[-1]
    assert "candidate context" in tokenizer.prompts[-1]


def test_native_causal_generation_rejects_prefix_corruption():
    service = NativeCausalLMGenerationService(
        tokenizer=FakeTokenizer(),
        model=PrefixMismatchModel(),
        max_new_tokens=64,
    )

    with pytest.raises(NativeCausalLMGenerationError, match="does not preserve"):
        service.generate([{"role": "user", "content": "hello"}])


