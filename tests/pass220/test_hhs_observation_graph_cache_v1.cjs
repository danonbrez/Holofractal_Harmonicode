"use strict";
const assert=require("node:assert/strict");
const {loadRenderingUMD}=require("./load_rendering_umd_v1.cjs");
const {ObservationCache}=loadRenderingUMD("hhs_observation_graph_cache_v1.js");
const A="a".repeat(216),B="b".repeat(216),C="c".repeat(216),D="d".repeat(216);
const validation=bytes=>({compatibilityUnadmitted:false,vm81AdmissionAuthority:false,frameIndex:BigInt(bytes[0]),exactTimeNum:BigInt(bytes[0]),exactTimeDen:120n});
const record=(n,hash)=>({nativeAdmission:true,matrixVersion:n,decayHash216:A,frameHash216:hash,packet:new Uint8Array([n])});
assert.throws(()=>new ObservationCache(),/OBS_NATIVE_VALIDATOR_REQUIRED/);
const cache=new ObservationCache({capacity:2,validatePacket:validation});
assert.throws(()=>cache.append({...record(1,B),nativeAdmission:false}),/OBS_NOT_ADMITTED/);
cache.append(record(1,B));cache.append(record(2,C));
assert.equal(cache.length,2);
assert.equal(cache.bracket(3,240).exact,false);
assert.equal(cache.bracket(2,120).exact,true);
assert.equal(cache.bracket(3,120),null);
assert.throws(()=>cache.append(record(2,D)),/OBS_REPLAY_OR_OUT_OF_ORDER/);
const copy=cache.lookup(B);copy.packet[0]=255;
assert.equal(cache.lookup(B).packet[0],1);
cache.append(record(3,D));
assert.equal(cache.lookup(B),null);
assert.equal(cache.snapshot().canonicalMutationAuthority,false);
assert.throws(()=>new ObservationCache({validatePacket:()=>({compatibilityUnadmitted:true})}).append(record(1,B)),/OBS_PACKET_NOT_NATIVE_ADMITTED/);
assert.throws(()=>new ObservationCache({validatePacket:validation}).append({...record(1,B),timeNum:4}),/OBS_TIME_MISMATCH/);
assert.throws(()=>new ObservationCache({validatePacket:validation}).append({...record(1,B),decayHash216:"not-a-native-hash"}),/OBS_INVALID_DECAY_HASH216/);
console.log("PASS: presentation observation cache - 13 assertions");
