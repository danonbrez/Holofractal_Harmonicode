def test_pass219_prototype_compilation_is_cached(monkeypatch):
    import hhs_runtime.hhs_pass219_ethical_text_training_v1 as training

    calls = {"from_repository": 0, "compile": 0, "select": 0}

    class FakeCycle:
        @classmethod
        def from_repository(cls, *args, **kwargs):
            calls["from_repository"] += 1
            return cls()

        def compile_dataset(self, examples, require_word2vec=True):
            calls["compile"] += 1
            return {
                "dataset_hash72": "d" * 72,
                "final_hash216_root": "f" * 64,
                "records": [{
                    "example_id": "prototype-1",
                    "prompt": "What is language?",
                }],
            }

        def select_response_candidate(self, query, dataset, top_k=3):
            calls["select"] += 1
            return {
                "candidate_set_hash72": "c" * 72,
                "results": [{
                    "example_id": "prototype-1",
                    "score": {"numerator": 1, "denominator": 2},
                    "response": "Language carries structured meaning.",
                    "record_hash72": "r" * 72,
                    "hash216_root": "h" * 64,
                    "declared_invariants": ["TRUTH_PRESERVATION"],
                }],
            }

    monkeypatch.setattr(training, "EthicalTextTrainingCycle", FakeCycle)
    monkeypatch.setattr(training, "load_prompt_response_jsonl", lambda path: [object()])

    provider = HHSNativeLiteRTLMTransport(
        word2vec_service=FakeWord2Vec(),
        require_word2vec=False,
        generation_service=FakeGenerationService(),
    )

    first_context, first_meta = provider._prototype_context("language")
    second_context, second_meta = provider._prototype_context("meaning")

    assert first_context
    assert second_context
    assert calls["from_repository"] == 1
    assert calls["compile"] == 1
    assert calls["select"] == 2
    assert first_meta["prototype_dataset_reused"] is False
    assert second_meta["prototype_dataset_reused"] is True



class SlowGenerationService(FakeGenerationService):
    def generate(self, messages, *, retrieval_context=None, max_new_tokens=None):
        import time as _time
        _time.sleep(0.2)
        return super().generate(
            messages,
            retrieval_context=retrieval_context,
            max_new_tokens=max_new_tokens,
        )


class FailingGenerationService(FakeGenerationService):
    def generate(self, messages, *, retrieval_context=None, max_new_tokens=None):
        raise NativeCausalLMNotReady("forced unavailable causal model")


